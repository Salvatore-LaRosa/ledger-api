package dev.salvatore.ledger.domain.ledger;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.assertj.core.api.Assertions.tuple;

import dev.salvatore.ledger.domain.account.Account;
import dev.salvatore.ledger.domain.account.AccountType;
import dev.salvatore.ledger.domain.exception.ReversalNotAllowedException;
import dev.salvatore.ledger.domain.ledger.LedgerTransaction.EntryDraft;
import java.util.Currency;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

class LedgerTransactionReversalTest {

    private static final Currency EUR = Currency.getInstance("EUR");

    private final Account customer = Account.open("customer", AccountType.CUSTOMER, EUR);
    private final Account merchant = Account.open("merchant", AccountType.MERCHANT, EUR);

    @Test
    void reverseMirrorsEveryEntryWithTheOppositeDirection() {
        LedgerTransaction original = persisted(payment());

        LedgerTransaction reversal = original.reverse("reversal:test");

        assertThat(reversal.getReference()).isEqualTo("reversal:test");
        assertThat(reversal.getReversalOfId()).isEqualTo(original.getId());
        assertThat(reversal.getEntries())
                .extracting(LedgerEntry::getAccount, LedgerEntry::getDirection, LedgerEntry::getAmount)
                .containsExactlyInAnyOrder(
                        tuple(customer, EntryDirection.CREDIT, 2_500L),
                        tuple(merchant, EntryDirection.DEBIT, 2_500L));
    }

    @Test
    void reverseLeavesTheOriginalUntouched() {
        LedgerTransaction original = persisted(payment());

        original.reverse("reversal:test");

        assertThat(original.getReversalOfId()).isNull();
        assertThat(original.getEntries())
                .extracting(LedgerEntry::getAccount, LedgerEntry::getDirection, LedgerEntry::getAmount)
                .containsExactlyInAnyOrder(
                        tuple(customer, EntryDirection.DEBIT, 2_500L),
                        tuple(merchant, EntryDirection.CREDIT, 2_500L));
    }

    @Test
    void aTransactionThatWasNeverPersistedCannotBeReversed() {
        LedgerTransaction original = payment();

        assertThatThrownBy(() -> original.reverse("reversal:test"))
                .isInstanceOf(IllegalStateException.class);
    }

    @Test
    void aReversalCannotBeReversed() {
        LedgerTransaction reversal = persisted(persisted(payment()).reverse("reversal:first"));

        assertThatThrownBy(() -> reversal.reverse("reversal:second"))
                .isInstanceOf(ReversalNotAllowedException.class);
    }

    @Test
    void aBlankReferenceIsRejected() {
        LedgerTransaction original = persisted(payment());

        assertThatThrownBy(() -> original.reverse("   "))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void oppositeFlipsTheDirection() {
        assertThat(EntryDirection.DEBIT.opposite()).isEqualTo(EntryDirection.CREDIT);
        assertThat(EntryDirection.CREDIT.opposite()).isEqualTo(EntryDirection.DEBIT);
    }

    private LedgerTransaction payment() {
        return LedgerTransaction.create("pay:1", List.of(
                EntryDraft.debit(customer, 2_500),
                EntryDraft.credit(merchant, 2_500)));
    }

    /** The id is generated by JPA on persist: simulate it. */
    private static LedgerTransaction persisted(LedgerTransaction transaction) {
        ReflectionTestUtils.setField(transaction, "id", UUID.randomUUID());
        return transaction;
    }
}